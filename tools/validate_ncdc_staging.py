#!/usr/bin/env python3
"""Quality-gate NCDC outbreak staging CSVs before human verification.

Reads the staging CSV generated by ncdc_preview_import.py and writes a separate
QA CSV and JSON summary. Never modifies PostgreSQL or overwrites the source CSV.
No extracted row is auto-approved for database import; all rows remain subject to
comparison with the original NCDC report.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from collections import Counter
from datetime import datetime
from pathlib import Path

STATE_NAMES = [
    "Andhra Pradesh", "Arunachal Pradesh", "Assam", "Bihar", "Chhattisgarh",
    "Goa", "Gujarat", "Haryana", "Himachal Pradesh", "Jharkhand", "Karnataka",
    "Kerala", "Madhya Pradesh", "Maharashtra", "Manipur", "Meghalaya", "Mizoram",
    "Nagaland", "Odisha", "Punjab", "Rajasthan", "Sikkim", "Tamil Nadu",
    "Telangana", "Tripura", "Uttar Pradesh", "Uttarakhand", "West Bengal",
    "Andaman and Nicobar Islands", "Chandigarh",
    "Dadra and Nagar Haveli and Daman and Diu", "Delhi", "Jammu and Kashmir",
    "Ladakh", "Lakshadweep", "Puducherry",
]
STATE_BY_COMPACT = {re.sub(r"[^a-z]", "", name.lower()): name for name in STATE_NAMES}
STATE_ALIASES = {
    "orissa": "Odisha", "uttaranchal": "Uttarakhand", "pondicherry": "Puducherry",
    "nctofdelhi": "Delhi", "jammuandkashmir": "Jammu and Kashmir",
}

DATE_PATTERNS = [
    re.compile(r"^(\d{4})-(\d{1,2})-(\d{1,2})$"),
    re.compile(r"^(\d{1,2})\s*-\s*(\d{1,2})\s*-\s*(\d{4})$"),
    re.compile(r"^(\d{1,2})/(\d{1,2})/(\d{4})$"),
]
RECORD_ID_RE = re.compile(r"^.+/(?P<year>20\d{2})/(?P<week>\d{1,2})/\d+$", re.I)
# A one- or two-letter token embedded inside longer disease words commonly indicates
# a PDF cell split such as "Haemorrhagi c Fever" or "Gastroenterit is".
FRAGMENT_RE = re.compile(r"\b[A-Za-z]{5,}\s+[A-Za-z]{1,2}\b")


def clean(value: object) -> str:
    return re.sub(r"\s+", " ", str(value or "").replace("\xa0", " ")).strip()


def suggest_state(raw: str) -> str:
    value = clean(raw)
    compact = re.sub(r"[^a-z]", "", value.lower())
    if compact in STATE_BY_COMPACT:
        return STATE_BY_COMPACT[compact]
    return STATE_ALIASES.get(compact, "")


def valid_int(value: str) -> bool:
    text = clean(value).replace(",", "")
    return bool(re.fullmatch(r"\d+", text))


def valid_date(value: str) -> bool:
    text = clean(value)
    for index, pattern in enumerate(DATE_PATTERNS):
        m = pattern.fullmatch(text)
        if not m:
            continue
        nums = [int(x) for x in m.groups()]
        if index == 0:
            y, mo, d = nums
        else:
            d, mo, y = nums
        try:
            datetime(y, mo, d)
            return True
        except ValueError:
            return False
    return False


def review_reasons(row: dict[str, str], duplicate_id: bool = False) -> tuple[list[str], str]:
    reasons: list[str] = []
    raw_state = clean(row.get("state", ""))
    proposed_state = suggest_state(raw_state)
    if not raw_state:
        reasons.append("state is blank; likely column alignment problem")
    elif not proposed_state:
        reasons.append("state does not match a recognized Indian state/UT; verify against PDF")
    elif raw_state.casefold() != proposed_state.casefold():
        reasons.append(f"state normalization suggestion: {raw_state!r} -> {proposed_state!r}; verify against PDF")

    for field in ("district", "disease"):
        value = clean(row.get(field, ""))
        if not value:
            reasons.append(f"{field} is blank")
        if re.search(r"\d", value):
            reasons.append(f"{field} contains digits; check column alignment")
    disease = clean(row.get("disease", ""))
    if FRAGMENT_RE.search(disease):
        reasons.append("disease text appears split across cells/lines; verify and repair from PDF")

    cases = clean(row.get("cases", ""))
    if not valid_int(cases):
        reasons.append("cases is blank or not a non-negative integer")
    deaths = clean(row.get("deaths", ""))
    if deaths and not valid_int(deaths):
        reasons.append("deaths is not a non-negative integer")

    for field in ("outbreak_start_date", "reporting_date"):
        value = clean(row.get(field, ""))
        if not valid_date(value):
            reasons.append(f"{field} is blank or not a valid parsed date")

    if not clean(row.get("current_status", "")):
        reasons.append("current_status is blank")

    match = RECORD_ID_RE.fullmatch(clean(row.get("record_id", "")))
    if not match:
        reasons.append("record_id format is unexpected")
    else:
        for row_field, id_field in (("report_year", "year"), ("report_week", "week")):
            row_value = clean(row.get(row_field, ""))
            if not row_value.isdigit() or int(row_value) != int(match.group(id_field)):
                reasons.append(f"{row_field} does not match record_id")

    if duplicate_id:
        reasons.append("duplicate record_id in staging CSV")
    return reasons, proposed_state


def run(input_path: Path, output_path: Path | None = None) -> tuple[Path, Path]:
    if not input_path.is_file():
        raise FileNotFoundError(f"Input staging CSV not found: {input_path}")
    output_path = output_path or input_path.with_name(input_path.stem + "_qa.csv")
    summary_path = output_path.with_suffix(".summary.json")

    with input_path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames:
            raise ValueError("Input CSV is missing a header row")
        rows = list(reader)

    counts = Counter(clean(r.get("record_id", "")) for r in rows)
    qa_rows = []
    reason_counts: Counter[str] = Counter()
    flagged = 0
    for row in rows:
        record_id = clean(row.get("record_id", ""))
        duplicate = bool(record_id and counts[record_id] > 1)
        reasons, proposed_state = review_reasons(row, duplicate)
        qa_status = "needs_review" if reasons else "source_verification_required"
        if reasons:
            flagged += 1
            reason_counts.update(reasons)
        enriched = dict(row)
        enriched["proposed_state_normalization"] = proposed_state
        enriched["qa_status"] = qa_status
        enriched["qa_reasons"] = " | ".join(reasons)
        enriched["database_import_approved"] = "no"
        qa_rows.append(enriched)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = list(qa_rows[0].keys()) if qa_rows else list(csv.DictReader(input_path.open(encoding="utf-8-sig")).fieldnames or []) + [
        "proposed_state_normalization", "qa_status", "qa_reasons", "database_import_approved"
    ]
    with output_path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(qa_rows)

    summary = {
        "input_csv": str(input_path.resolve()),
        "qa_csv": str(output_path.resolve()),
        "generated_at_utc": datetime.utcnow().isoformat(timespec="seconds") + "Z",
        "rows_examined": len(rows),
        "rows_needing_review": flagged,
        "rows_without_automatic_flags_still_need_source_pdf_verification": len(rows) - flagged,
        "duplicate_record_ids": sorted(k for k, n in counts.items() if k and n > 1),
        "common_review_reasons": [{"reason": k, "count": v} for k, v in reason_counts.most_common()],
        "database_modified": False,
        "database_import_approved": False,
        "policy": "No row is auto-approved. Compare every row against the official source PDF before import.",
    }
    summary_path.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print("NCDC staging quality check complete.")
    print(f"Rows examined: {len(rows)}")
    print(f"Rows needing review: {flagged}")
    print(f"Rows still requiring PDF verification: {len(rows)}")
    print(f"QA CSV: {output_path.resolve()}")
    print(f"Summary: {summary_path.resolve()}")
    print("Database modified: no")
    return output_path, summary_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="staging CSV from ncdc_preview_import.py")
    parser.add_argument("--output", type=Path, default=None, help="QA output CSV (default: <input>_qa.csv)")
    args = parser.parse_args()
    try:
        run(args.input, args.output)
    except Exception as exc:
        parser.exit(2, f"QA failed: {type(exc).__name__}: {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
